import { stringify } from "yaml";
import type { ScaffolderConfig } from "./config";
import { buildView } from "./view";

type Obj = Record<string, unknown>;

const HEADER = `# Generated by Scaffolder. Edit freely; regenerate with \`scaffolder generate\` to diff.
# One compose file serves local dev (build:) and deploys (image: pulled from the registry).
`;

export function buildCompose(cfg: ScaffolderConfig): string {
  const v = buildView(cfg);
  const services: Obj = {};
  const volumes: Obj = {};

  if (v.hasDb) {
    services.postgres = {
      image: v.dbImage,
      environment: {
        POSTGRES_USER: "${POSTGRES_USER:-" + v.db.user + "}",
        POSTGRES_PASSWORD: "${POSTGRES_PASSWORD:-" + v.db.password + "}",
        POSTGRES_DB: "${POSTGRES_DB:-" + v.db.name + "}",
      },
      // Bound to loopback: reachable from the host for debugging, never from the network.
      ports: ["127.0.0.1:${POSTGRES_PORT:-5432}:5432"],
      volumes: ["pg_data:/var/lib/postgresql/data"],
      healthcheck: {
        test: ["CMD-SHELL", "pg_isready -U $${POSTGRES_USER} -d $${POSTGRES_DB}"],
        interval: "5s",
        timeout: "3s",
        retries: 10,
      },
      restart: "unless-stopped",
    };
    volumes.pg_data = {};
  }

  if (cfg.backend.enabled) {
    const backend: Obj = {
      image: "${BACKEND_IMAGE:-" + v.slug + "-backend:local}",
      build: { context: `./${v.backendDir}` },
      environment: {
        APP_ENV: "${APP_ENV:-development}",
        CORS_ORIGINS: "${CORS_ORIGINS:-http://localhost:" + v.webPort + "}",
        ...(v.hasDb
          ? {
              DATABASE_URL:
                "postgresql+asyncpg://${POSTGRES_USER:-" + v.db.user + "}:${POSTGRES_PASSWORD:-" + v.db.password +
                "}@postgres:5432/${POSTGRES_DB:-" + v.db.name + "}",
            }
          : {}),
      },
      ports: ["${BACKEND_PORT:-" + v.backendPort + "}:8000"],
      healthcheck: {
        test: ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health', timeout=3)"],
        interval: "5s",
        timeout: "5s",
        retries: 12,
        start_period: "10s",
      },
      restart: "unless-stopped",
    };
    if (v.hasDb) backend.depends_on = { postgres: { condition: "service_healthy" } };
    services.backend = backend;
  }

  if (cfg.web.enabled) {
    services.web = {
      image: "${WEB_IMAGE:-" + v.slug + "-web:local}",
      build: { context: `./${v.webDir}` },
      environment: {
        // Resolved at request time (not build time): one image runs in every environment.
        API_URL: "${API_URL:-http://backend:8000}",
      },
      ports: ["${WEB_PORT:-" + v.webPort + "}:3000"],
      depends_on: { backend: { condition: "service_healthy" } },
      healthcheck: {
        test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"],
        interval: "5s",
        timeout: "5s",
        retries: 12,
        start_period: "10s",
      },
      restart: "unless-stopped",
    };
  }

  const doc: Obj = { name: v.slug, services };
  if (Object.keys(volumes).length > 0) doc.volumes = volumes;
  return HEADER + stringify(doc, { lineWidth: 0 });
}

export function buildEnvExample(cfg: ScaffolderConfig): string {
  const v = buildView(cfg);
  const lines = [
    "# Copy to .env for local overrides. NEVER commit .env or real credentials.",
    "# Every value below has a safe development default in docker-compose.yml.",
    "APP_ENV=development",
  ];
  if (cfg.backend.enabled) {
    lines.push(`BACKEND_PORT=${v.backendPort}`, `CORS_ORIGINS=http://localhost:${v.webPort}`);
  }
  if (cfg.web.enabled) {
    lines.push(`WEB_PORT=${v.webPort}`, `API_URL=http://backend:8000`);
  }
  if (v.hasDb) {
    lines.push(
      "",
      "# Database (development defaults; use real secrets in deployed environments)",
      `POSTGRES_USER=${v.db.user}`,
      `POSTGRES_PASSWORD=${v.db.password}`,
      `POSTGRES_DB=${v.db.name}`,
      "POSTGRES_PORT=5432",
      "",
      "# Used when running the backend directly on the host (outside Docker)",
      `DATABASE_URL=${v.databaseUrlLocal}`,
    );
  }
  return lines.join("\n") + "\n";
}
