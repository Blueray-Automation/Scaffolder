type Json = Record<string, unknown>;

function isPlainObject(v: unknown): v is Json {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Deep-merge `patch` over `base`. Arrays and scalars in `patch` replace. */
export function deepMerge<T>(base: T, patch: unknown): T {
  if (!isPlainObject(base) || !isPlainObject(patch)) {
    return (patch === undefined ? base : (patch as T));
  }
  const out: Json = { ...base };
  for (const [key, value] of Object.entries(patch)) {
    out[key] = key in base ? deepMerge((base as Json)[key], value) : value;
  }
  return out as T;
}

export function sanitizeName(name: string): string {
  const cleaned = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^-+|-+$/g, "");
  return cleaned || "my-ai-project";
}

/** Merge user input over defaults and apply derived defaults (e.g. DB version for a type). */
export function resolveConfig(input: unknown = {}): ScaffolderConfig {
  const merged = deepMerge(defaultConfig(), input);
  merged.project.name = sanitizeName(String(merged.project.name));

  const db = findOption(CAPABILITIES.database, merged.database.type);
  if (db?.versions && !db.versions.includes(merged.database.version)) {
    merged.database.version = db.versions[0];
  }
  return merged;
}

const SLUG = /^[a-z][a-z0-9-]{1,48}$/;
const DIR = /^[A-Za-z0-9][A-Za-z0-9._/-]*$/;

export function validateConfig(cfg: ScaffolderConfig): Issue[] {
  const issues: Issue[] = [];
  const err = (path: string, message: string) => issues.push({ level: "error", path, message });
  const warn = (path: string, message: string) => issues.push({ level: "warning", path, message });

  if (cfg.version !== CONFIG_VERSION) {
    err("version", `Unsupported config version ${cfg.version}; this engine understands ${CONFIG_VERSION}.`);
  }
  if (!SLUG.test(cfg.project.name)) {
    err("project.name", "Must be 2-49 chars: lowercase letters, digits and dashes, starting with a letter.");
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9-]{0,38}$/.test(cfg.project.owner)) {
    err("project.owner", "Must be a valid GitHub user/org name (letters, digits, dashes).");
  }
  if (!findOption(CAPABILITIES.license, cfg.project.license)) {
    err("project.license", `Unknown license. Choose one of: ${CAPABILITIES.license.map((l) => l.id).join(", ")}.`);
  }

  // Layout
  for (const key of ["backendDir", "webDir"] as const) {
    const dir = cfg.layout[key];
    if (!DIR.test(dir) || dir.includes("..") || dir.endsWith("/")) {
      err(`layout.${key}`, "Must be a relative path without '..' and without a trailing slash.");
    }
  }
  if (cfg.layout.backendDir === cfg.layout.webDir) {
    err("layout.webDir", "backendDir and webDir must differ.");
  }

  // Components
  if (!cfg.backend.enabled && !cfg.web.enabled && !cfg.mobile.enabled) {
    err("backend.enabled", "Enable at least one component (backend, web or mobile).");
  }
  if (cfg.mobile.enabled) {
    err("mobile.enabled", "Mobile packs are not available yet. Disable mobile to generate.");
  }
  if (cfg.web.enabled && !cfg.backend.enabled) {
    err("web.enabled", "A web-only project is not supported yet: the web app needs the backend API.");
  }

  if (cfg.backend.enabled) {
    const lang = findOption(CAPABILITIES.backend.languages, cfg.backend.language);
    if (!lang) {
      err("backend.language", `Unknown language "${cfg.backend.language}".`);
    } else if (!lang.available) {
      err("backend.language", `${lang.label} is not available yet. Available: ${availableIds(CAPABILITIES.backend.languages).join(", ")}.`);
    } else {
      const fw = findOption(lang.frameworks, cfg.backend.framework);
      if (!fw || !fw.available) {
        err("backend.framework", `"${cfg.backend.framework}" is not available for ${lang.label}. Available: ${availableIds(lang.frameworks).join(", ")}.`);
      } else if (!fw.versions.includes(cfg.backend.version)) {
        err("backend.version", `${fw.label} supports versions: ${fw.versions.join(", ")}.`);
      }
    }
  }

  if (cfg.web.enabled) {
    const fw = findOption(CAPABILITIES.web.frameworks, cfg.web.framework);
    if (!fw || !fw.available) {
      err("web.framework", `"${cfg.web.framework}" is not available yet. Available: ${availableIds(CAPABILITIES.web.frameworks).join(", ")}.`);
    } else if (!fw.versions.includes(cfg.web.nodeVersion)) {
      err("web.nodeVersion", `Supported Node versions: ${fw.versions.join(", ")}.`);
    }
    if (!cfg.web.typescript) {
      err("web.typescript", "JavaScript-only mode is not available yet; the generated web app is TypeScript.");
    }
  }

  const db = findOption(CAPABILITIES.database, cfg.database.type);
  if (!db || !db.available) {
    err("database.type", `"${cfg.database.type}" is not available yet. Available: ${availableIds(CAPABILITIES.database).join(", ")}.`);
  } else if (db.versions && !db.versions.includes(cfg.database.version)) {
    err("database.version", `${db.label} supports versions: ${db.versions.join(", ")}.`);
  }
  if (cfg.database.type !== "none" && !cfg.backend.enabled) {
    err("database.type", "A database needs the backend component enabled.");
  }

  for (const [path, list, id] of [
    ["cache.type", CAPABILITIES.cache, cfg.cache.type],
    ["auth.type", CAPABILITIES.auth, cfg.auth.type],
    ["ci.provider", CAPABILITIES.ci, cfg.ci.provider],
    ["cd.registry", CAPABILITIES.registry, cfg.cd.registry],
    ["cd.target", CAPABILITIES.deployTarget, cfg.cd.target],
    ["sdlc.runtime", CAPABILITIES.runtime, cfg.sdlc.runtime],
  ] as const) {
    const opt = findOption(list, id);
    if (!opt) err(path, `Unknown value "${id}".`);
    else if (!opt.available) err(path, `${opt.label} is not available yet. Available: ${availableIds(list).join(", ")}.`);
  }

  // Ports
  const ports: Array<[string, number]> = [];
  if (cfg.backend.enabled) ports.push(["backend.port", cfg.backend.port]);
  if (cfg.web.enabled) ports.push(["web.port", cfg.web.port]);
  const seen = new Map<number, string>();
  for (const [path, port] of ports) {
    if (!Number.isInteger(port) || port < 1024 || port > 65535) {
      err(path, "Must be an integer between 1024 and 65535.");
    } else if (seen.has(port)) {
      err(path, `Port ${port} is already used by ${seen.get(port)}.`);
    } else {
      seen.set(port, path);
    }
  }

  // Docker / CI / CD coupling
  if (cfg.sdlc.runtime === "docker" && !cfg.docker.enabled) {
    err("sdlc.runtime", 'Runtime "docker" needs docker.enabled = true (or choose runtime "local" / "none").');
  }
  if (cfg.cd.enabled) {
    if (!cfg.docker.enabled) err("cd.enabled", "CD builds container images and needs docker.enabled = true.");
    if (cfg.ci.provider !== "github-actions") err("cd.enabled", "CD workflows are only generated for GitHub Actions.");
    if (cfg.cd.registry === "none") warn("cd.registry", "Registry is none: images are built but not published, so nothing can be deployed.");
    if (cfg.cd.environments.length === 0) err("cd.environments", "Define at least one environment or disable CD.");
  }
  const envNames = new Set<string>();
  cfg.cd.environments.forEach((env, i) => {
    if (!/^[a-z][a-z0-9-]{0,30}$/.test(env.name)) err(`cd.environments[${i}].name`, "Use lowercase letters, digits and dashes.");
    if (envNames.has(env.name)) err(`cd.environments[${i}].name`, `Duplicate environment "${env.name}".`);
    envNames.add(env.name);
    if (!["push-default-branch", "tag", "manual"].includes(env.trigger)) {
      err(`cd.environments[${i}].trigger`, "Must be push-default-branch, tag or manual.");
    }
    try {
      new URL(env.url);
    } catch {
      err(`cd.environments[${i}].url`, "Must be an absolute URL (used for post-deploy fact probes).");
    }
  });
  if (cfg.ci.provider === "none" && cfg.cd.enabled) {
    err("ci.provider", "CD needs a CI provider.");
  }
  if (!/^[A-Za-z0-9._/-]+$/.test(cfg.ci.defaultBranch)) err("ci.defaultBranch", "Invalid branch name.");

  // SDLC loop
  const s = cfg.sdlc;
  if (!Number.isInteger(s.maxIterations) || s.maxIterations < 1 || s.maxIterations > 20) {
    err("sdlc.maxIterations", "Must be an integer between 1 and 20.");
  }
  if (!Number.isInteger(s.noProgressLimit) || s.noProgressLimit < 1 || s.noProgressLimit > 10) {
    err("sdlc.noProgressLimit", "Must be an integer between 1 and 10.");
  }
  if (!Number.isInteger(s.agent.timeoutSeconds) || s.agent.timeoutSeconds < 30 || s.agent.timeoutSeconds > 7200) {
    err("sdlc.agent.timeoutSeconds", "Must be between 30 and 7200 seconds.");
  }
  for (const key of ["backend", "web"] as const) {
    const v = s.coverage[key];
    if (typeof v !== "number" || v < 0 || v > 100) err(`sdlc.coverage.${key}`, "Must be between 0 and 100.");
  }
  if (!s.gates.facts && s.runtime !== "none") {
    warn("sdlc.gates.facts", "Fact verification is disabled: PRD acceptance criteria will not be checked.");
  }
  if (s.agent.command && /[\r\n]/.test(s.agent.command)) {
    err("sdlc.agent.command", "Must be a single-line shell command.");
  }

  return issues;
}

export function hasErrors(issues: Issue[]): boolean {
  return issues.some((i) => i.level === "error");
}
