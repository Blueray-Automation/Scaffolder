import { CAPABILITIES, availableIds, findOption } from "./capabilities";

export const CONFIG_VERSION = 1;

export type BackendLanguage = "python" | "node" | "java" | "go";
export type WebFramework = "nextjs" | "react" | "vue" | "nuxt";
export type MobileFramework = "flutter" | "react-native";
export type DatabaseType = "none" | "postgres" | "mysql" | "mongodb";
export type CacheType = "none" | "redis";
export type AuthType = "none" | "jwt" | "session" | "keycloak";
export type CiProvider = "github-actions" | "gitlab-ci" | "none";
export type RegistryType = "ghcr" | "dockerhub" | "none";
export type DeployTarget = "none" | "ssh-compose" | "kubernetes";
export type RuntimeMode = "docker" | "local" | "none";
export type DeployTrigger = "push-default-branch" | "tag" | "manual";

export interface Environment {
  /** GitHub Environment name, e.g. "staging". */
  name: string;
  /** Public base URL used for post-deploy fact probes. */
  url: string;
  trigger: DeployTrigger;
}

export interface ScaffolderConfig {
  version: number;
  project: {
    name: string;
    description: string;
    /** GitHub org/user. Used for the GHCR image path. */
    owner: string;
    license: "MIT" | "UNLICENSED";
  };
  layout: {
    backendDir: string;
    webDir: string;
  };
  backend: {
    enabled: boolean;
    language: BackendLanguage;
    framework: string;
    version: string;
    port: number;
  };
  web: {
    enabled: boolean;
    framework: WebFramework;
    typescript: boolean;
    nodeVersion: string;
    port: number;
  };
  mobile: {
    enabled: boolean;
    framework: MobileFramework;
  };
  database: {
    type: DatabaseType;
    version: string;
  };
  cache: { type: CacheType };
  auth: { type: AuthType };
  docker: { enabled: boolean };
  ci: {
    provider: CiProvider;
    defaultBranch: string;
  };
  cd: {
    enabled: boolean;
    registry: RegistryType;
    target: DeployTarget;
    environments: Environment[];
  };
  sdlc: {
    /** Max verify→heal iterations before the loop gives up. */
    maxIterations: number;
    /** Stop when the same failure repeats this many iterations in a row. */
    noProgressLimit: number;
    /** Stop at the first failing stage instead of running every gate. */
    failFast: boolean;
    runtime: RuntimeMode;
    agent: {
      /** Shell command that reads the prompt on stdin. Empty = human-in-the-loop. */
      command: string;
      timeoutSeconds: number;
    };
    coverage: { backend: number; web: number };
    gates: {
      lint: boolean;
      types: boolean;
      unit: boolean;
      build: boolean;
      contract: boolean;
      facts: boolean;
      security: boolean;
    };
    /** Extra files/dirs the agent may not modify while healing (added to the built-in set). */
    protectedPaths: string[];
  };
}

export type IssueLevel = "error" | "warning";

export interface Issue {
  level: IssueLevel;
  path: string;
  message: string;
}

