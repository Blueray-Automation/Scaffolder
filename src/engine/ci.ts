import { stringify } from "yaml";
import type { ScaffolderConfig, Environment } from "./config";
import { buildGates, setupSteps, type Gate } from "./gates";
import { buildView } from "./view";

type Obj = Record<string, unknown>;

const HEADER = `# Generated by Scaffolder from the same gate definitions as .ai/sdlc.json,
# so a green \`./scripts/sdlc verify\` locally and a green pipeline mean the same thing.
`;

function gateStep(gate: Gate): Obj {
  const step: Obj = { name: gate.label, run: gate.cmd };
  if (gate.cwd !== ".") step["working-directory"] = gate.cwd;
  if (gate.env) step.env = gate.env;
  if (!gate.required) step["continue-on-error"] = true;
  return step;
}

function backendJob(cfg: ScaffolderConfig): Obj {
  const dir = cfg.layout.backendDir;
  const setup = setupSteps(cfg).find((s) => s.component === "backend")!;
  const gates = buildGates(cfg).filter((g) => g.component === "backend");
  return {
    name: "Backend verify",
    "runs-on": "ubuntu-latest",
    "timeout-minutes": 20,
    steps: [
      { uses: "actions/checkout@v4" },
      {
        uses: "actions/setup-python@v5",
        with: { "python-version": cfg.backend.version, cache: "pip", "cache-dependency-path": `${dir}/pyproject.toml` },
      },
      { name: setup.label, run: setup.cmd, "working-directory": setup.cwd },
      { name: "Put the venv on PATH", run: `echo "$GITHUB_WORKSPACE/${dir}/.venv/bin" >> "$GITHUB_PATH"` },
      ...gates.map(gateStep),
    ],
  };
}

function webJob(cfg: ScaffolderConfig): Obj {
  const setup = setupSteps(cfg).find((s) => s.component === "web")!;
  const gates = buildGates(cfg).filter((g) => g.component === "web");
  return {
    name: "Web verify",
    "runs-on": "ubuntu-latest",
    "timeout-minutes": 20,
    steps: [
      { uses: "actions/checkout@v4" },
      // Enable `cache: npm` here once web/package-lock.json is committed.
      { uses: "actions/setup-node@v4", with: { "node-version": cfg.web.nodeVersion } },
      { name: setup.label, run: setup.cmd, "working-directory": setup.cwd },
      ...gates.map(gateStep),
    ],
  };
}

function repoJob(cfg: ScaffolderConfig): Obj | null {
  const gates = buildGates(cfg).filter((g) => g.component === "repo");
  if (gates.length === 0) return null;
  return {
    name: "Repository checks",
    "runs-on": "ubuntu-latest",
    "timeout-minutes": 10,
    steps: [
      { uses: "actions/checkout@v4" },
      { uses: "actions/setup-python@v5", with: { "python-version": "3.12" } },
      ...gates.map(gateStep),
    ],
  };
}

function factsJob(cfg: ScaffolderConfig, needs: string[]): Obj {
  const local = cfg.sdlc.runtime === "local";
  const steps: Obj[] = [
    { uses: "actions/checkout@v4" },
    { uses: "actions/setup-python@v5", with: { "python-version": cfg.backend.enabled ? cfg.backend.version : "3.12" } },
  ];
  if (local) {
    if (cfg.web.enabled) steps.push({ uses: "actions/setup-node@v4", with: { "node-version": cfg.web.nodeVersion } });
    steps.push(
      { name: "Install dependencies", run: "python3 scripts/sdlc.py setup" },
      { name: "Build (needed by the local runtime)", run: "python3 scripts/sdlc.py gates --stage build" },
    );
  }
  steps.push(
    {
      name: "Verify PRD facts against the running system",
      run: "python3 scripts/sdlc.py facts",
    },
    {
      name: "Publish evidence report",
      if: "always()",
      run: 'if [ -f .ai/evidence/latest/report.md ]; then cat .ai/evidence/latest/report.md >> "$GITHUB_STEP_SUMMARY"; fi',
    },
    {
      name: "Upload evidence",
      if: "always()",
      uses: "actions/upload-artifact@v4",
      with: { name: "sdlc-evidence", path: ".ai/evidence/", "if-no-files-found": "ignore", "retention-days": 14 },
    },
  );
  return { name: "Facts (PRD → running system)", "runs-on": "ubuntu-latest", needs, "timeout-minutes": 30, steps };
}

export function buildCiWorkflow(cfg: ScaffolderConfig): string {
  const jobs: Obj = {};
  if (cfg.backend.enabled) jobs.backend = backendJob(cfg);
  if (cfg.web.enabled) jobs.web = webJob(cfg);
  const repo = repoJob(cfg);
  if (repo) jobs.repo = repo;
  const needs = Object.keys(jobs);
  if (cfg.sdlc.gates.facts && cfg.sdlc.runtime !== "none" && (cfg.backend.enabled || cfg.web.enabled)) {
    jobs.facts = factsJob(cfg, needs);
  }

  const triggers: Obj = {
    pull_request: { branches: [cfg.ci.defaultBranch] },
    workflow_dispatch: {},
    // Lets cd.yml gate image builds on the exact same checks.
    workflow_call: {},
  };
  // With CD enabled, pushes to the default branch run CI through cd.yml (once, not twice).
  if (!cfg.cd.enabled) triggers.push = { branches: [cfg.ci.defaultBranch] };

  const doc: Obj = {
    name: "CI",
    on: triggers,
    concurrency: { group: "ci-${{ github.workflow }}-${{ github.ref }}", "cancel-in-progress": true },
    permissions: { contents: "read" },
    jobs,
  };
  return HEADER + stringify(doc, { lineWidth: 0 });
}

function envCondition(env: Environment, defaultBranch: string): string {
  const dispatched = `(github.event_name == 'workflow_dispatch' && inputs.environment == '${env.name}')`;
  if (env.trigger === "push-default-branch") {
    return `(github.event_name == 'push' && github.ref == 'refs/heads/${defaultBranch}') || ${dispatched}`;
  }
  if (env.trigger === "tag") {
    return `(github.event_name == 'push' && startsWith(github.ref, 'refs/tags/v')) || ${dispatched}`;
  }
  return dispatched;
}

export function buildCdWorkflow(cfg: ScaffolderConfig): string {
  const v = buildView(cfg);
  const dir = { backend: cfg.layout.backendDir, web: cfg.layout.webDir };
  const publish = cfg.cd.registry === "ghcr";

  const buildSteps: Obj[] = [
    { uses: "actions/checkout@v4" },
    { uses: "docker/setup-buildx-action@v3" },
  ];
  if (publish) {
    buildSteps.push({
      uses: "docker/login-action@v3",
      with: { registry: "ghcr.io", username: "${{ github.actor }}", password: "${{ secrets.GITHUB_TOKEN }}" },
    });
  }
  buildSteps.push({
    name: "Compute immutable image tag",
    id: "meta",
    run: [
      'TAG="sha-${GITHUB_SHA::12}"',
      'echo "tag=$TAG" >> "$GITHUB_OUTPUT"',
      'if [[ "$GITHUB_REF" == refs/tags/v* ]]; then echo "release=${GITHUB_REF#refs/tags/}" >> "$GITHUB_OUTPUT"; fi',
    ].join("\n"),
  });
  for (const [component, image] of [
    ["backend", v.imageBackend],
    ["web", v.imageWeb],
  ] as const) {
    if (!cfg[component].enabled) continue;
    const tags = [`${image}:\${{ steps.meta.outputs.tag }}`];
    const tagList = tags.join("\n") + `\n${image}:latest`;
    buildSteps.push({
      name: `Build${publish ? " & push" : ""} ${component} image`,
      uses: "docker/build-push-action@v6",
      with: {
        context: `./${dir[component]}`,
        push: publish,
        tags: tagList,
        "cache-from": "type=gha",
        "cache-to": "type=gha,mode=max",
      },
    });
  }

  const jobs: Obj = {
    ci: { name: "CI gate", uses: "./.github/workflows/ci.yml" },
    images: {
      name: "Build images (once)",
      needs: "ci",
      "runs-on": "ubuntu-latest",
      permissions: { contents: "read", packages: "write" },
      outputs: { tag: "${{ steps.meta.outputs.tag }}" },
      steps: buildSteps,
    },
  };

  for (const env of cfg.cd.environments) {
    jobs[`deploy-${env.name}`] = {
      name: `Deploy → ${env.name}`,
      needs: "images",
      if: envCondition(env, cfg.ci.defaultBranch),
      "runs-on": "ubuntu-latest",
      // Configure required reviewers on this GitHub Environment to add an approval gate.
      environment: { name: env.name, url: env.url },
      concurrency: { group: `deploy-${env.name}`, "cancel-in-progress": false },
      steps: [
        { uses: "actions/checkout@v4" },
        { uses: "actions/setup-python@v5", with: { "python-version": "3.12" } },
        {
          name: `Deploy image \${{ needs.images.outputs.tag }} to ${env.name}`,
          run: `./scripts/deploy.sh ${env.name} "$IMAGE_TAG"`,
          env: {
            IMAGE_TAG: "${{ needs.images.outputs.tag }}",
            DEPLOY_HOST: "${{ secrets.DEPLOY_HOST }}",
            DEPLOY_USER: "${{ secrets.DEPLOY_USER }}",
            DEPLOY_PATH: "${{ secrets.DEPLOY_PATH }}",
            DEPLOY_SSH_KEY: "${{ secrets.DEPLOY_SSH_KEY }}",
          },
        },
        // A placeholder target deploys nothing, so there is no live URL to verify yet.
        ...(cfg.sdlc.gates.facts && cfg.web.enabled && cfg.cd.target !== "none"
          ? [
              {
                name: "Post-deploy fact check against the live URL",
                run: `python3 scripts/sdlc.py facts --no-runtime --base-url web=${env.url} --label ${env.name}`,
              },
              {
                name: "Upload evidence",
                if: "always()",
                uses: "actions/upload-artifact@v4",
                with: { name: `evidence-${env.name}`, path: ".ai/evidence/", "if-no-files-found": "ignore", "retention-days": 30 },
              },
            ]
          : []),
      ],
    };
  }

  const triggers: Obj = {
    push: {
      branches: [cfg.ci.defaultBranch],
      ...(cfg.cd.environments.some((e) => e.trigger === "tag") ? { tags: ["v*.*.*"] } : {}),
    },
    workflow_dispatch: {
      inputs: {
        environment: {
          description: "Environment to deploy to",
          required: true,
          type: "choice",
          options: cfg.cd.environments.map((e) => e.name),
        },
      },
    },
  };

  const doc: Obj = {
    name: "CD",
    on: triggers,
    concurrency: { group: "cd-${{ github.ref }}", "cancel-in-progress": false },
    permissions: { contents: "read" },
    jobs,
  };
  return HEADER + stringify(doc, { lineWidth: 0 });
}
