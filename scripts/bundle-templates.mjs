#!/usr/bin/env node
// Bundles templates/**/*.tmpl into src/engine/templates.generated.ts so the engine
// stays a pure function that runs unchanged in the browser, the CLI and tests.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = join(repo, "templates");
const outFile = join(repo, "src", "engine", "templates.generated.ts");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const files = {};
const stray = [];
for (const full of walk(templatesDir)) {
  const key = relative(templatesDir, full).split(sep).join("/");
  if (key.endsWith("/.DS_Store") || key === ".DS_Store") continue;
  if (!key.endsWith(".tmpl")) {
    stray.push(key);
    continue;
  }
  files[key] = { content: readFileSync(full, "utf8") };
}

if (stray.length > 0) {
  console.error(`Template files must end in .tmpl (so tooling ignores them):\n  ${stray.join("\n  ")}`);
  process.exit(1);
}

const body =
  "// AUTO-GENERATED by scripts/bundle-templates.mjs from templates/. Do not edit.\n" +
  "export const TEMPLATE_FILES: Record<string, { content: string }> = " +
  JSON.stringify(files, null, 1) +
  ";\n";

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`bundled ${Object.keys(files).length} templates -> ${relative(repo, outFile)}`);
